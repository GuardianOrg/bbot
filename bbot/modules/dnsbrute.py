import asyncio
import time
from pathlib import Path

from bbot.errors import WordlistError
from bbot.modules.templates.subdomain_enum import subdomain_enum


class dnsbrute(subdomain_enum):
    flags = ["subdomain-enum", "active", "aggressive"]
    watched_events = ["DNS_NAME"]
    produced_events = ["DNS_NAME"]
    meta = {
        "description": "Brute-force subdomains with massdns + static wordlist",
        "author": "@TheTechromancer",
        "created_date": "2024-04-24",
    }
    options = {
        "wordlist": "",
        "wordlists": [],
        "max_words": 10000,
        "child_words": 1000,
        "max_depth": 5,
        "dns_batch_size": 1000,
    }
    options_desc = {
        "wordlist": "Wordlist path/URL; empty uses the bundled ranked list without HTTP",
        "wordlists": "Additional wordlist paths/URLs merged in order with exact deduplication",
        "max_words": "Maximum unique words retained across all lists",
        "child_words": "Maximum highest-ranked words tried beneath each non-apex parent",
        "max_depth": "How many subdomains deep to brute force, i.e. 5.4.3.2.1.evilcorp.com",
        "dns_batch_size": "Maximum labels per A/AAAA batch; small batches allow other discovery modules to progress",
    }
    deps_common = ["massdns"]
    reject_wildcards = False
    dedup_strategy = "lowest_parent"
    _qsize = 10000

    async def _fetch_required_wordlist(self, fetcher, description):
        last_error = None
        for attempt in range(1, 4):
            try:
                return await fetcher()
            except WordlistError as e:
                last_error = e
                if attempt >= 3:
                    break
                self.warning(f"Failed to download {description} on attempt {attempt}/3: {e}")
                await asyncio.sleep(attempt)
        raise WordlistError(f"Failed to download {description} after 3 attempts: {last_error}")

    async def setup_deps(self):
        self.subdomain_file = await self._fetch_required_wordlist(
            lambda: self.helpers.wordlist(
                self.config.get("wordlist") or str(Path(__file__).parent.parent / "wordlists/subdomains-ranked.txt")
            ),
            "dnsbrute wordlist",
        )
        # tell the dnsbrute helper to fetch the resolver file
        await self._fetch_required_wordlist(
            lambda: self.helpers.dns.brute.prepare_resolvers(),
            "dnsbrute resolver list",
        )
        return True

    async def setup(self):
        self.max_depth = max(1, self.config.get("max_depth", 5))
        self.max_words = int(self.config.get("max_words", 10000))
        self.child_words = int(self.config.get("child_words", 1000))
        self.dns_batch_size = int(self.config.get("dns_batch_size", 1000))
        if self.max_words <= 0 or self.child_words <= 0 or not 0 < self.dns_batch_size <= 5000:
            raise ValueError("dnsbrute max_words and child_words must be positive")
        self.deferred = {}
        self.emitted_hosts = set()
        lists = [self.subdomain_file]
        for extra in self.config.get("wordlists", []):
            lists.append(await self.helpers.wordlist(extra))
        ordered = {}
        for wordlist in lists:
            for word in self.helpers.read_file(wordlist):
                word = word.strip().lower().rstrip(".")
                if word and not word.startswith("#"):
                    ordered.setdefault(word, None)
                if len(ordered) >= self.max_words:
                    break
            if len(ordered) >= self.max_words:
                break
        self.subdomain_list = list(ordered)
        self.wordlist_size = len(self.subdomain_list)
        return await super().setup()

    async def filter_event(self, event):
        brute = self.helpers.dns.brute
        if brute.deadline is not None and time.monotonic() >= brute.deadline:
            return False, "shared brute-force runtime budget exhausted"
        eligible, reason = await super().filter_event(event)
        query = self.make_query(event)

        # limit brute force depth
        subdomain_depth = self.helpers.subdomain_depth(query) + 1
        if subdomain_depth > self.max_depth:
            eligible = False
            reason = f"subdomain depth of *.{query} ({subdomain_depth}) > max_depth ({self.max_depth})"

        # don't brute-force things that look like autogenerated PTRs
        if self.helpers.dns.brute.has_excessive_digits(query):
            eligible = False
            reason = f'"{query}" looks like an autogenerated PTR'

        if eligible and not brute.remaining_candidates(self):
            if len(brute.queries_tried) < brute.max_candidates and len(self.deferred) < 100:
                self.deferred.setdefault(query, event)
            return False, "DNS work deferred for priority discovery reservations"
        return eligible, reason

    async def handle_event(self, event):
        query = self.make_query(event)
        words = (
            self.subdomain_list
            if query == self.helpers.split_domain(query)[1]
            else self.subdomain_list[: self.child_words]
        )
        self.info(f"Brute-forcing {len(words):,} subdomains for {query} (source: {event.data})")
        found = set()
        brute = self.helpers.dns.brute
        for offset in range(0, len(words), self.dns_batch_size):
            if not brute.remaining_candidates(self):
                if len(self.deferred) < 100 and len(brute.queries_tried) < brute.max_candidates:
                    self.deferred.setdefault(query, event)
                return
            batch = words[offset : offset + self.dns_batch_size]
            results = await asyncio.gather(*(brute(self, query, batch, type=kind) for kind in ("A", "AAAA")))
            for hostname in dict.fromkeys(host for group in results for host in group):
                if hostname in found or hostname in self.emitted_hosts:
                    continue
                found.add(hostname)
                self.emitted_hosts.add(hostname)
                await self.emit_event(
                    hostname,
                    "DNS_NAME",
                    parent=event,
                    context=f'{{module}} queried A/AAAA for {len(words):,} labels against "{query}" and found {{event.type}}: {{event.data}}',
                )
            if not brute.remaining_candidates(self) and len(brute.queries_tried) < brute.max_candidates:
                if len(self.deferred) < 100:
                    self.deferred.setdefault(query, event)
                return

    async def finish(self):
        brute = self.helpers.dns.brute
        if not self.deferred:
            return
        # Priority modules release unused reservations at their first finish.
        for name in list(brute.reservations):
            module = self.scan.modules.get(name)
            if module is None or module.errored:
                brute.release_reservation(name)
        remaining = brute.max_runtime if brute.deadline is None else brute.deadline - time.monotonic()
        if remaining <= 0:
            return
        try:
            await asyncio.wait_for(brute.reservations_released.wait(), remaining)
        except asyncio.TimeoutError:
            return
        pending, self.deferred = self.deferred, {}
        for event in pending.values():
            await self.handle_event(event)

    async def report(self):
        self.info(f"DNS discovery metrics: {self.helpers.dns.brute.metrics()}")
        helper = self.helpers.dns.brute
        self.info(
            f"DNS resolver metrics: {len(helper.resolver_pool.selected)} validated, {helper.resolver_pool.confirmations} confirmations, {helper.resolver_pool.rejected} rejected names, {helper.transport_failures} terminal transport failures, {helper.transport_retries} bounded retries, {helper.per_resolver_threads} slots/resolver/process"
        )
